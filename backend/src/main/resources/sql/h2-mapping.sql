SELECT c.ORDINAL_POSITION COLUMN_ID,c.COLUMN_NAME,c.DATA_TYPE,
 CASE WHEN c.DATA_TYPE LIKE 'TIMESTAMP%' THEN 19 WHEN c.DATA_TYPE='DATE' THEN 10
 ELSE c.CHARACTER_OCTET_LENGTH END DATA_LENGTH,c.CHARACTER_MAXIMUM_LENGTH CHAR_LENGTH,
 c.NUMERIC_PRECISION DATA_PRECISION,c.NUMERIC_SCALE DATA_SCALE,c.IS_NULLABLE,
 c.REMARKS FIELD_DESCRIPTION,c.COLUMN_DEFAULT DEFAULT_VALUE,
 c.DATA_TYPE SOURCE_DATA_TYPE,
 CASE WHEN c.DATA_TYPE LIKE 'TIMESTAMP%' THEN 19 WHEN c.DATA_TYPE='DATE' THEN 10
 WHEN c.DATA_TYPE IN ('TINYINT','SMALLINT','INTEGER','BIGINT') THEN
 CASE c.DATA_TYPE WHEN 'TINYINT' THEN 3 WHEN 'SMALLINT' THEN 5 WHEN 'INTEGER' THEN 10 ELSE 19 END
 WHEN c.DATA_TYPE IN ('NUMERIC','DECIMAL','REAL','DOUBLE PRECISION','FLOAT','DECFLOAT') THEN c.NUMERIC_PRECISION
 ELSE COALESCE(c.CHARACTER_MAXIMUM_LENGTH,c.CHARACTER_OCTET_LENGTH) END SOURCE_LENGTH,
 COALESCE(c.NUMERIC_SCALE,0) SOURCE_DECIMAL,
 CASE WHEN EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS t
 JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE k ON k.CONSTRAINT_CATALOG=t.CONSTRAINT_CATALOG AND k.CONSTRAINT_SCHEMA=t.CONSTRAINT_SCHEMA AND k.CONSTRAINT_NAME=t.CONSTRAINT_NAME
 WHERE t.TABLE_SCHEMA=c.TABLE_SCHEMA AND t.TABLE_NAME=c.TABLE_NAME AND k.COLUMN_NAME=c.COLUMN_NAME AND t.CONSTRAINT_TYPE='PRIMARY KEY') THEN 'PK' ELSE '' END PK_FLAG,
 CASE WHEN EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS t
 JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE k ON k.CONSTRAINT_CATALOG=t.CONSTRAINT_CATALOG AND k.CONSTRAINT_SCHEMA=t.CONSTRAINT_SCHEMA AND k.CONSTRAINT_NAME=t.CONSTRAINT_NAME
 WHERE t.TABLE_SCHEMA=c.TABLE_SCHEMA AND t.TABLE_NAME=c.TABLE_NAME AND k.COLUMN_NAME=c.COLUMN_NAME AND t.CONSTRAINT_TYPE='FOREIGN KEY') THEN 'FK' ELSE '' END FK_FLAG
FROM INFORMATION_SCHEMA.COLUMNS c
WHERE c.TABLE_SCHEMA=? AND c.TABLE_NAME=?
ORDER BY c.ORDINAL_POSITION
