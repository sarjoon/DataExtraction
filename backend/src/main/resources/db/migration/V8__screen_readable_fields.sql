-- Preserve the old table-based configuration without guessing its screen association.
ALTER TABLE readable_trigger_field RENAME TO legacy_readable_trigger_field;
CREATE TABLE readable_trigger_field (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id BIGINT NOT NULL REFERENCES connection_profile(id),
    screen_name VARCHAR(256) NOT NULL,
    field_name VARCHAR(128) NOT NULL,
    CONSTRAINT uq_readable_screen_field UNIQUE(connection_id, screen_name, field_name)
);
