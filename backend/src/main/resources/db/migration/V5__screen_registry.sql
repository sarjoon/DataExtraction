CREATE TABLE screen_registry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id BIGINT NOT NULL REFERENCES connection_profile(id),
    screen_name VARCHAR(256) NOT NULL,
    source VARCHAR(20) NOT NULL CHECK (source IN ('MANUAL','UPLOAD')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_registered_screen UNIQUE(connection_id, screen_name)
);
