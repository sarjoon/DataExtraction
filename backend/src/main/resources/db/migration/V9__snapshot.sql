CREATE TABLE snapshot_table (
 connection_id BIGINT NOT NULL REFERENCES connection_profile(id),
 table_name VARCHAR(128) NOT NULL,
 ignored_columns CLOB NOT NULL,
 PRIMARY KEY(connection_id,table_name)
);
-- Disk-backed working sets keep large primary-key lists and report rows out of the Java heap.
CREATE TABLE snapshot_key_stage (
 run_id VARCHAR(450) NOT NULL, table_name VARCHAR(128) NOT NULL,
 key_hash VARCHAR(64) NOT NULL, before_key_json CLOB, after_key_json CLOB,
 key_category INTEGER GENERATED ALWAYS AS (CASE WHEN before_key_json IS NULL THEN 1 WHEN after_key_json IS NULL THEN 0 ELSE 2 END),
 PRIMARY KEY(run_id,table_name,key_hash)
);
CREATE INDEX snapshot_key_categories ON snapshot_key_stage(run_id,table_name,key_category,key_hash);
CREATE TABLE snapshot_row_stage (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 run_id VARCHAR(450) NOT NULL, table_name VARCHAR(128) NOT NULL,
 category VARCHAR(20) NOT NULL, row_json CLOB NOT NULL
);
CREATE INDEX snapshot_rows_by_run ON snapshot_row_stage(run_id,table_name,category,id);
