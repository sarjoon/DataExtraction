CREATE TABLE snapshot_batch (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 connection_id BIGINT NOT NULL REFERENCES connection_profile(id),
 batch_name VARCHAR(80) NOT NULL,
 UNIQUE(connection_id,batch_name),
 UNIQUE(id,connection_id)
);
CREATE TABLE snapshot_batch_table (
 batch_id BIGINT NOT NULL,
 connection_id BIGINT NOT NULL,
 table_name VARCHAR(128) NOT NULL,
 PRIMARY KEY(batch_id,table_name),
 FOREIGN KEY(batch_id,connection_id) REFERENCES snapshot_batch(id,connection_id) ON DELETE CASCADE,
 FOREIGN KEY(connection_id,table_name) REFERENCES snapshot_table_registry(connection_id,table_name) ON DELETE CASCADE
);
-- Existing working configurations remain runnable as a named batch after upgrading.
