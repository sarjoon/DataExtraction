INSERT INTO snapshot_batch_table(batch_id,connection_id,table_name)
 SELECT b.id,t.connection_id,t.table_name FROM snapshot_table t
 JOIN snapshot_batch b ON b.connection_id=t.connection_id AND b.batch_name='Default';
