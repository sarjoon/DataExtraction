import { test, expect } from '@playwright/test';
test('saved Oracle configuration, encrypted credential editing and table lists',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/overview');
 await expect(page.getByText('Configuration DB ready',{exact:true})).toBeVisible();
 await page.screenshot({path:'test-results/overview.png',fullPage:true});
 await page.getByRole('link',{name:'Database connections'}).click();
 await expect(page.getByRole('checkbox',{name:'Read-only connection',exact:true})).toBeChecked();
 const name=`Browser test ${Date.now()}`;
 await page.getByLabel('Connection name',{exact:true}).fill(name);
 await page.getByLabel('Host',{exact:true}).fill('127.0.0.1');
 await page.getByLabel('Port',{exact:true}).fill('1');
 await page.getByLabel('Service name',{exact:true}).fill('TEST_ONLY');
 await page.getByLabel('Username',{exact:true}).fill('test_user');
 await page.getByLabel('Schema / owner',{exact:true}).fill('APP');
 await page.getByLabel('Oracle password',{exact:true}).fill('browser-test-secret');
 const saveResponse=page.waitForResponse(r=>r.url().endsWith('/api/connections')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Save connection',exact:true}).click();
 const saved=await (await saveResponse).json();
 expect(saved.databaseType).toBe('ORACLE');expect(saved.passwordSaved).toBe(true);
 expect(saved.readOnly).toBe(true);
 expect(JSON.stringify(saved)).not.toContain('browser-test-secret');
 await expect(page.getByRole('heading',{name:`Test ${name}`})).toBeVisible();
 await expect(page.getByLabel('Oracle password',{exact:true})).toHaveValue('');
 await page.getByRole('button',{name:'Edit connection',exact:true}).click();
 await expect(page.getByRole('checkbox',{name:'Read-only connection',exact:true})).toBeChecked();
 await page.getByRole('checkbox',{name:'Read-only connection',exact:true}).uncheck();
 await page.getByRole('combobox',{name:'Connection type',exact:true}).selectOption('SID');
 const accessUpdate=page.waitForResponse(r=>r.url().endsWith('/api/connections/'+saved.id)&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Update connection',exact:true}).click();
 expect((await (await accessUpdate).json()).readOnly).toBe(false);
 await expect(page.getByText('jdbc:oracle:thin:@127.0.0.1:1:TEST_ONLY',{exact:false})).toBeVisible();
 await page.getByRole('button',{name:'Test connection',exact:true}).click();
 // No Oracle instance is configured in this test: report failure, never fall back to H2.
 await expect(page.getByRole('alert')).toContainText('Oracle connection or query failed',{timeout:20000});
 await page.screenshot({path:'test-results/connections.png',fullPage:true});
 await page.getByRole('link',{name:'Manage tables'}).click();
 await page.getByLabel('Table names',{exact:true}).fill('CUSTOMER\nACCOUNT\ncustomer');
 await page.getByRole('button',{name:'Append tables',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('2 table(s) added. 1 duplicate(s) skipped.');
 await page.locator('input[type=file]').setInputFiles({name:'tables.csv',mimeType:'text/csv',buffer:Buffer.from('Table Name,Schema\nCUSTOMER,APP\nPAYMENT,APP')});
 await page.getByRole('button',{name:'Upload & append',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('1 table(s) added. 1 duplicate(s) skipped.');
 await page.getByLabel('Table names',{exact:true}).fill('NEW_TABLE\nINVALID-NAME');
 await page.getByRole('button',{name:'Append tables',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('Names must start');
 await expect(page.getByRole('cell',{name:'NEW_TABLE',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Discover & append',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('Oracle connection or query failed',{timeout:20000});
 await expect(page.getByRole('cell',{name:'CONNECTION_PROFILE',exact:true})).toHaveCount(0);
 await page.reload();
 await expect(page.getByRole('cell',{name:'PAYMENT',exact:true})).toBeVisible();
 await page.getByLabel('Search tables',{exact:true}).fill('CUSTOMER');
 await expect(page.locator('tbody tr')).toHaveCount(1);
 await page.getByLabel('Search tables',{exact:true}).fill('');
 await page.screenshot({path:'test-results/tables.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'test-results/mobile.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 expect(errors).toEqual([]);
});
test('H2 console loads and logs in without frame or CSRF rejection',async({page})=>{
 await page.goto('/h2-console/');
 await expect(page.locator('input[name=url]')).toBeVisible();
 await page.locator('input[name=url]').fill(process.env['EDAC_E2E_H2_URL'] || 'jdbc:h2:file:./data/edac');
 await page.locator('input[name=user]').fill('sa');
 await page.locator('input[name=password]').fill('');
 await page.locator('input[type=submit]').first().click();
 await expect(page.locator('frame[name=h2menu]')).toHaveCount(1);
 await expect(page.frameLocator('frame[name=h2menu]').locator('body')).toContainText('CONNECTION_PROFILE');
});
